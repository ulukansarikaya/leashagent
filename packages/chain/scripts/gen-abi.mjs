// Regenerates src/abi.ts from Forge build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";

const out = (name) => JSON.parse(readFileSync(new URL(`../out/${name}.sol/${name}.json`, import.meta.url)));
let src = "// GENERATED by scripts/gen-abi.mjs from Forge output — do not edit by hand.\n\n";
for (const name of ["PolicyRegistry", "DecisionLog"]) {
  const j = out(name);
  src += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(j.abi, null, 2)} as const;\n\n`;
  src += `export const ${name[0].toLowerCase() + name.slice(1)}Bytecode = "${j.bytecode.object}" as const;\n\n`;
}
writeFileSync(new URL("../src/abi.ts", import.meta.url), src);
console.log("wrote src/abi.ts");
